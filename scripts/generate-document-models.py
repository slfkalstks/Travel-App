#!/usr/bin/env python3
"""Generate document DTOs from the canonical local schemas (stdlib only)."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = {
    "urn:travel-app:document": ROOT / "contracts/document.schema.json",
    "urn:travel-app:document-update": ROOT / "contracts/document-update.schema.json",
}
ROOT_KEYS = {"$schema", "$id", "title", "description", "type", "additionalProperties", "properties", "required"}
FIELD_KEYS = {"$ref", "type", "description", "default", "enum", "minLength", "maxLength", "pattern", "format", "minimum", "maximum"}


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def read_schemas():
    schemas = {key: json.loads(path.read_text(encoding="utf-8")) for key, path in SCHEMAS.items()}
    for identifier, schema in schemas.items():
        if set(schema) - ROOT_KEYS or schema.get("$id") != identifier or schema.get("type") != "object" or schema.get("additionalProperties") is not False:
            raise ValueError("Unsupported root schema: expected a closed flat object with its allowlisted ID")
        fields, required = schema.get("properties"), schema.get("required")
        if not isinstance(fields, dict) or not fields or not isinstance(required, list) or set(required) != fields.keys():
            raise ValueError("All document wire fields must be required")
        for name, raw in fields.items():
            if not re.fullmatch(r"[a-z][A-Za-z0-9]*", name) or not isinstance(raw, dict) or set(raw) - FIELD_KEYS:
                raise ValueError(f"Unsupported field: {name}")
            rule = resolve(raw, schemas)
            if rule.get("type") not in ("string", "integer"):
                raise ValueError(f"Unsupported type for {name}")
            if rule.get("format") not in (None, "uuid", "date-time"):
                raise ValueError(f"Unsupported format for {name}")
            if "enum" in rule and (rule["type"] != "string" or not rule["enum"] or any(not isinstance(item, str) for item in rule["enum"])):
                raise ValueError(f"Unsupported enum for {name}")
            for key in ("minLength", "maxLength", "minimum", "maximum"):
                if key in rule and (type(rule[key]) is not int or rule[key] < 0):
                    raise ValueError(f"Unsupported {key} for {name}")
            if "pattern" in rule:
                re.compile(rule["pattern"])
            if "default" in rule and not isinstance(rule["default"], str):
                raise ValueError(f"Unsupported default for {name}")
    return schemas


def resolve(rule, schemas):
    if "$ref" not in rule:
        return rule
    if set(rule) - {"$ref", "default"}:
        raise ValueError("Reference siblings may only specify a constructor default")
    match = re.fullmatch(r"(urn:travel-app:document-update)#/properties/([a-z][A-Za-z0-9]*)", rule["$ref"])
    if not match or match[1] not in schemas or match[2] not in schemas[match[1]]["properties"]:
        raise ValueError("Only allowlisted local document-update property references are supported")
    target = schemas[match[1]]["properties"][match[2]]
    if "$ref" in target:
        raise ValueError("Nested schema references are unsupported")
    return {**target, **{key: value for key, value in rule.items() if key != "$ref"}}


def generate(package, class_name, identifier, schemas, server):
    request = identifier.endswith("-update")
    fields = {name: resolve(rule, schemas) for name, rule in schemas[identifier]["properties"].items()}
    lines = ["// Generated by scripts/generate-document-models.py. Do not edit.",
             "// Authority: " + str(SCHEMAS[identifier].relative_to(ROOT)), f"package {package}", ""]
    if server and request:
        lines += ["import com.fasterxml.jackson.annotation.JsonAnySetter", "import com.fasterxml.jackson.core.JsonParser",
                  "import com.fasterxml.jackson.core.JsonToken", "import com.fasterxml.jackson.databind.DeserializationContext",
                  "import com.fasterxml.jackson.databind.JsonDeserializer", "import com.fasterxml.jackson.databind.JsonMappingException",
                  "import com.fasterxml.jackson.databind.annotation.JsonDeserialize", "import jakarta.validation.constraints.NotBlank",
                  "import jakarta.validation.constraints.Pattern", "import jakarta.validation.constraints.Size", ""]
    elif not server:
        lines += ["import kotlinx.serialization.Serializable", "", "@Serializable"]
    lines.append(f"data class {class_name}(")
    for index, (name, rule) in enumerate(fields.items()):
        if server and request:
            lines.append("    @param:JsonDeserialize(using = DocumentStringDeserializer::class)")
            if rule.get("minLength", 0) > 0:
                lines.append("    @field:NotBlank")
            lengths = [f"{label} = {rule[key]}" for key, label in (("minLength", "min"), ("maxLength", "max")) if key in rule]
            if lengths:
                lines.append(f"    @field:Size({', '.join(lengths)})")
            if "pattern" in rule:
                lines.append(f"    @field:Pattern(regexp = {kotlin_string(rule['pattern'])})")
        kind = "Long" if rule["type"] == "integer" else "String"
        default = " = " + kotlin_string(rule["default"]) if "default" in rule else ""
        comma = "," if index < len(fields) - 1 else ""
        lines.append(f"    val {name}: {kind}{default}{comma}")
    lines.append(")")
    if server and request:
        lines[-1] = ") {"
        lines += ["    @JsonAnySetter", '    fun rejectUnknown(property: String, @Suppress("UNUSED_PARAMETER") value: Any?) {',
                  '        throw IllegalArgumentException("알 수 없는 문서 입력 항목이에요: $property")', "    }", "}", "",
                  "class DocumentStringDeserializer : JsonDeserializer<String>() {",
                  "    override fun deserialize(parser: JsonParser, context: DeserializationContext): String {",
                  "        if (!parser.hasToken(JsonToken.VALUE_STRING)) {",
                  '            throw JsonMappingException.from(parser, "문서 입력값은 문자열이어야 해요.")', "        }",
                  "        return parser.text", "    }", "",
                  "    override fun getNullValue(context: DeserializationContext): String =",
                  '        throw JsonMappingException.from(context.parser, "문서 입력값은 문자열이어야 해요.")', "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on stale generated DTOs; write nothing")
    args = parser.parse_args()
    try:
        schemas = read_schemas()
        outputs = {}
        for server, folder, package in [(False, "app/composeApp/src/commonMain/kotlin/com/travel/app/data", "com.travel.app.data"),
                                         (True, "backend/src/main/kotlin/com/yeohaeng/demo", "com.yeohaeng.demo")]:
            for identifier, class_name in [("urn:travel-app:document", "DocumentRecord"),
                                           ("urn:travel-app:document-update", "DocumentUpdateRequest" if server else "DocumentUpdateInput")]:
                outputs[ROOT / folder / (class_name + ".kt")] = generate(package, class_name, identifier, schemas, server)
        stale = []
        for path, source in outputs.items():
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != source:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(source, encoding="utf-8")
        if stale:
            raise ValueError("Stale generated document DTOs:\n" + "\n".join(stale))
        print("Document DTOs are current." if args.check else "Generated document DTOs.")
        return 0
    except (ValueError, TypeError, KeyError, OSError) as error:
        print(f"Document generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
