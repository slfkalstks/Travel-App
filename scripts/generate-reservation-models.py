#!/usr/bin/env python3
"""Generate reservation request DTOs from the canonical schema (stdlib only)."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "contracts/reservation-input.schema.json"
ROOT_KEYS = {"$schema", "$id", "title", "description", "type", "additionalProperties", "properties", "required"}
FIELD_KEYS = {"type", "description", "default", "enum", "minLength", "maxLength", "pattern", "format"}


def kotlin_string(value):
    # JSON escaping is compatible here except for Kotlin's interpolation marker.
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def read_fields():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    if set(schema) - ROOT_KEYS or schema.get("type") != "object" or schema.get("additionalProperties") is not False:
        raise ValueError("Unsupported root schema: expected a closed flat object")
    fields = schema.get("properties")
    required = schema.get("required")
    if not isinstance(fields, dict) or not fields or not isinstance(required, list) or not set(required) <= fields.keys():
        raise ValueError("Invalid properties/required")
    for name, rule in fields.items():
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*", name):
            raise ValueError(f"Unsupported Kotlin property name: {name}")
        if not isinstance(rule, dict) or set(rule) - FIELD_KEYS or rule.get("type") != "string":
            raise ValueError(f"Unsupported schema for {name}: only constrained String fields are supported")
        if rule.get("format") not in (None, "date"):
            raise ValueError(f"Unsupported format for {name}")
        if "enum" in rule and (not rule["enum"] or any(not isinstance(item, str) for item in rule["enum"])):
            raise ValueError(f"Unsupported enum for {name}")
        if any(type(rule[key]) is not int or rule[key] < 0 for key in ("minLength", "maxLength") if key in rule):
            raise ValueError(f"Unsupported length for {name}")
        if "pattern" in rule and not isinstance(rule["pattern"], str):
            raise ValueError(f"Unsupported pattern for {name}")
        if "default" in rule and not isinstance(rule["default"], str):
            raise ValueError(f"Unsupported default for {name}")
        if name not in required and "default" not in rule:
            raise ValueError(f"Optional field {name} must have an explicit String default")
        if name in required and "default" in rule:
            raise ValueError(f"Required field {name} cannot have a constructor default")
    return fields, set(required)


def generate(package, class_name, fields, required, server):
    lines = ["// Generated by scripts/generate-reservation-models.py. Do not edit.",
             "// Authority: contracts/reservation-input.schema.json", f"package {package}", ""]
    if server:
        lines += ["import com.fasterxml.jackson.annotation.JsonAnySetter", "import com.fasterxml.jackson.core.JsonParser",
                  "import com.fasterxml.jackson.core.JsonToken", "import com.fasterxml.jackson.databind.DeserializationContext",
                  "import com.fasterxml.jackson.databind.JsonDeserializer", "import com.fasterxml.jackson.databind.JsonMappingException",
                  "import com.fasterxml.jackson.databind.annotation.JsonDeserialize",
                  "import jakarta.validation.constraints.NotBlank", "import jakarta.validation.constraints.Pattern",
                  "import jakarta.validation.constraints.Size", ""]
    else:
        lines += ["import kotlinx.serialization.Serializable", "", "@Serializable"]
    lines.append(f"data class {class_name}(")
    for index, (name, rule) in enumerate(fields.items()):
        if server:
            lines.append("    @param:JsonDeserialize(using = ReservationStringDeserializer::class)")
            if name in required:
                lines.append("    @field:NotBlank")
            lengths = [f"{label} = {rule[key]}" for key, label in (("minLength", "min"), ("maxLength", "max")) if key in rule]
            if lengths:
                lines.append(f"    @field:Size({', '.join(lengths)})")
            pattern = rule.get("pattern")
            if "enum" in rule:
                if pattern:
                    raise ValueError(f"Cannot combine enum and pattern for {name}")
                pattern = "^(?:" + "|".join(re.escape(value) for value in rule["enum"]) + ")$"
            if pattern:
                lines.append(f"    @field:Pattern(regexp = {kotlin_string(pattern)})")
        default = "" if name in required else " = " + kotlin_string(rule["default"])
        comma = "," if index < len(fields) - 1 else ""
        lines.append(f"    val {name}: String{default}{comma}")
    if server:
        lines += [") {", "    @JsonAnySetter", '    fun rejectUnknown(property: String, @Suppress("UNUSED_PARAMETER") value: Any?) {',
                  '        throw IllegalArgumentException("알 수 없는 예약 입력 항목이에요: $property")', "    }", "}", "",
                  "class ReservationStringDeserializer : JsonDeserializer<String>() {",
                  "    override fun deserialize(parser: JsonParser, context: DeserializationContext): String {",
                  "        if (!parser.hasToken(JsonToken.VALUE_STRING)) {",
                  '            throw JsonMappingException.from(parser, "예약 입력값은 문자열이어야 해요.")',
                  "        }", "        return parser.text", "    }", "",
                  "    override fun getNullValue(context: DeserializationContext): String =",
                  '        throw JsonMappingException.from(context.parser, "예약 입력값은 문자열이어야 해요.")', "}"]
    else:
        lines.append(")")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in generated files differ; write nothing")
    args = parser.parse_args()
    try:
        fields, required = read_fields()
        outputs = {
            ROOT / "app/composeApp/src/commonMain/kotlin/com/travel/app/data/ReservationInput.kt":
                generate("com.travel.app.data", "ReservationInput", fields, required, False),
            ROOT / "backend/src/main/kotlin/com/yeohaeng/demo/ReservationRequest.kt":
                generate("com.yeohaeng.demo", "ReservationRequest", fields, required, True),
        }
        stale = []
        for path, source in outputs.items():
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != source:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(source, encoding="utf-8")
        if stale:
            print("Stale generated reservation DTOs:\n" + "\n".join(stale), file=sys.stderr)
            return 1
        print("Reservation DTOs are current." if args.check else "Generated reservation DTOs.")
        return 0
    except (ValueError, TypeError, KeyError, OSError) as error:
        print(f"Reservation generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
